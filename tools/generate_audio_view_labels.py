"""Generate a one-BRAM Chinese title strip, without consuming UART glyph IDs."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ImageFont.truetype('C:/Windows/Fonts/simsun.ttc', 16)
LABELS = ['音频波形·42.7ms·自适应', '声音强弱 · 近6.4秒']
rows = []
preview = Image.new('RGB', (512, 64), '#101e2c')
for mode, label in enumerate(LABELS):
    im = Image.new('1', (256, 16))
    draw = ImageDraw.Draw(im)
    assert draw.textbbox((0, -2), label, font=FONT)[2] <= 256
    draw.text((0, -2), label, fill=1, font=FONT)
    for y in range(16):
        for word in range(16):
            rows.append(sum(1 << (15-x) for x in range(16) if im.getpixel((word*16+x, y))))
    colored = Image.new('RGB', im.size, '#60e8b0')
    preview.paste(colored, (12, mode*32+8), im)

body = ['// Generated by tools/generate_audio_view_labels.py.',
        '// address = {history_mode, row[3:0], word[3:0]}. 512 x 16 bits.',
        '(* rom_style = "bram" *) reg [15:0] audio_label_rom [0:511];',
        'initial begin']
body += [f" audio_label_rom[{i}] <= 16'h{v:04x};" for i, v in enumerate(rows)]
body += ['end', '']
(ROOT/'src/user_source/hdl_source/audio/audio_view_labels.vh').write_text('\n'.join(body), encoding='ascii')
out = ROOT/'verification/static_wavegain_20261002'
out.mkdir(exist_ok=True)
preview.save(out/'audio_labels_preview.png')
print('Audio labels: 512 x 16 bits; UART font mapping unchanged.')
